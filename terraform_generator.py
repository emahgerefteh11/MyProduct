def generate_terraform(report_path: pathlib.Path, output_dir: pathlib.Path, provider_filter: str = "auto", clean: bool = False):
    """Main execution function generating modular Terraform configurations from report_data.json."""
    if not report_path.exists():
        raise FileNotFoundError(f"Report file not found: {report_path}")

    with open(report_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if clean and output_dir.exists():
        shutil.rmtree(output_dir)

    output_dir.mkdir(parents=True, exist_ok=True)

    platforms = data.get("platforms", [])
    total_stacks_generated = 0

    print(f"Reading infrastructure topology from {report_path}...")
    print(f"Target Output Directory: {output_dir.resolve()}\n")

    for platform_data in platforms:
        platform_name = platform_data.get("Platform", "unknown")
        products = platform_data.get("products", [])

        for product_data in products:
            product_name = product_data.get("Product", "unknown")
            environments = product_data.get("environments", [])
            services = product_data.get("services", [])

            if not environments:
                environments = [{"environment": "default"}]

            # Determine cloud provider for this stack
            if provider_filter != "auto":
                target_provider = provider_filter.lower()
            else:
                target_provider = detect_stack_provider(platform_name, product_data)

            instance_type = get_primary_compute_sku(product_data, target_provider)

            for env_data in environments:
                env_name = env_data.get("Environment", "default")
                stack_dir = output_dir / sanitize_name(platform_name) / sanitize_name(product_name) / sanitize_name(env_name)
                stack_dir.mkdir(parents=True, exist_ok=True)

                if target_provider == "azure":
                    stack_files = build_azure_stack(platform_name, product_name, env_name, instance_type, services)
                elif target_provider == "gcp":
                    stack_files = build_gcp_stack(platform_name, product_name, env_name, instance_type, services)
                else:
                    stack_files = build_aws_stack(platform_name, product_name, env_name, instance_type, services)

                for filename, file_content in stack_files.items():
                    target_file = stack_dir / filename
                    target_file.write_text(file_content, encoding="utf-8")

                total_stacks_generated += 1
                print(f"  [+] Vended {target_provider.upper()} Stack: {stack_dir.relative_to(output_dir)} (SKU: {instance_type})")

    print(f"\nSuccessfully vended {total_stacks_generated} modular Terraform stack(s) into {output_dir}")


def main():
    parser = argparse.ArgumentParser(
        description="Generate modular, SKU-aware Terraform configurations from Cloud Cost Atlas report data."
    )
    parser.add_argument(
        "--input",
        "-i",
        type=pathlib.Path,
        default=pathlib.Path("report_data.json"),
        help="Path to report_data.json (default: report_data.json)",
    )
    parser.add_argument(
        "--output-dir",
        "-o",
        type=pathlib.Path,
        default=pathlib.Path("terraform_generated"),
        help="Output directory for generated Terraform configurations (default: terraform_generated)",
    )
    parser.add_argument(
        "--provider",
        "-p",
        choices=["auto", "aws", "azure", "gcp"],
        default="auto",
        help="Target cloud provider for generated stacks (default: auto)",
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Clean existing target directory before generation",
    )
    args = parser.parse_args()

    # Fallback to MyProduct/report_data.json if report_data.json not found in current directory
    input_path = args.input
    if not input_path.exists() and pathlib.Path("MyProduct/report_data.json").exists():
        input_path = pathlib.Path("MyProduct/report_data.json")

    generate_terraform(input_path, args.output_dir, args.provider, args.clean)


if __name__ == "__main__":
    main()
